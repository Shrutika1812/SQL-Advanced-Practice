-- INDEX NOTES

-- Indexes can improve read/search performance.
-- They are commonly useful on columns frequently used in:
-- WHERE, JOIN, ORDER BY and sometimes GROUP BY clauses.

-- Indexes also have a cost:
-- 1. They require additional storage.
-- 2. INSERT/UPDATE/DELETE operations may become more expensive.
-- 3. Too many indexes can reduce write performance.

-- Always analyze query performance before adding indexes.
